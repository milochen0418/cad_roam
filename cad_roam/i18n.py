def kind_title(kind: str, lang: str) -> str:
    titles = KIND_TITLES.get(kind)
    if titles:
        return titles.get(lang) or titles["en"]
    return kind


def ago(seconds: float, lang: str) -> str:
    """"5 minutes ago" / " 5 分鐘前"."""
    s = max(0, int(seconds))
    zh = lang == "zh-TW"
    for size, en, tw in ((86400 * 365, "year", "年"), (86400 * 30, "month", "個月"), (86400, "day", "天"), (3600, "hour", "小時"), (60, "minute", "分鐘")):
        if s >= size:
            n = s // size
            return f" {n} {tw}前" if zh else f"{n} {en}{'s' if n > 1 else ''} ago"
    return "剛剛" if zh else "just now"
